# Odpověď je HTML: odstavce <p>, kroky <ol>, poznámky <p class="note">.

def P(*parts):
    return "".join(f"<p>{x}</p>" for x in parts)

def OL(*steps):
    return "<ol>" + "".join(f"<li>{s}</li>" for s in steps) + "</ol>"

def UL(*items):
    return "<ul>" + "".join(f"<li>{s}</li>" for s in items) + "</ul>"

def NOTE(t):
    return f'<p class="note"><b>Pozor:</b> {t}</p>'

